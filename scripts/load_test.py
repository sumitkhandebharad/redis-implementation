#!/usr/bin/env python3
"""Small dependency-free load test for the Redis Cache product API."""

from __future__ import annotations

import argparse
import concurrent.futures
import json
import math
import statistics
import sys
import threading
import random
import time
import urllib.error
import urllib.request
from collections import Counter


def request(url: str, method: str = "GET", body: dict | None = None, timeout: float = 5.0):
    payload = json.dumps(body).encode() if body is not None else None
    req = urllib.request.Request(url, data=payload, method=method)
    if payload is not None:
        req.add_header("Content-Type", "application/json")
    started = time.perf_counter()
    try:
        with urllib.request.urlopen(req, timeout=timeout) as response:
            content = response.read()
            return response.status, time.perf_counter() - started, None, content
    except urllib.error.HTTPError as exc:
        exc.read()
        return exc.code, time.perf_counter() - started, None, exc.read()
    except Exception as exc:  # Report network/timeout errors as results, not worker crashes.
        return None, time.perf_counter() - started, f"{type(exc).__name__}: {exc}", b""


def percentile(values: list[float], p: float) -> float:
    if not values:
        return 0.0
    ordered = sorted(values)
    return ordered[max(0, math.ceil(p * len(ordered)) - 1)]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base-url", default="http://localhost:8080", help="Application base URL")
    parser.add_argument("--product-id", type=int, help="Existing product ID; otherwise create a load-test product")
    parser.add_argument("--concurrency", type=int, default=20, help="Concurrent worker threads (default: 20)")
    parser.add_argument("--duration", type=float, default=30, help="Measurement duration in seconds (default: 30)")
    parser.add_argument("--timeout", type=float, default=5, help="Per-request timeout in seconds")
    parser.add_argument("--mode", choices=("warm", "miss", "mixed", "random", "write"), default="warm",
                        help="warm: one cache hit; miss: nonexistent IDs/404; mixed: warm hits + 404s; random: hits across a product pool; write: POST creates")
    parser.add_argument("--pool-size", type=int, default=100,
                        help="Number of products in random-read pool (default: 100)")
    parser.add_argument("--setup-only", action="store_true", help="Create a product, print its ID, then exit")
    args = parser.parse_args()

    if args.concurrency < 1 or args.duration <= 0 or args.timeout <= 0 or args.pool_size < 1:
        parser.error("concurrency, duration, timeout, and pool-size must be positive")
    base = args.base_url.rstrip("/")
    api = f"{base}/api/products"
    product_id = args.product_id
    product_ids: list[int] = []
    if args.mode == "write":
        product_id = product_id or 0
    elif args.mode == "random":
        if product_id is not None:
            product_ids.append(product_id)
        while len(product_ids) < args.pool_size:
            ordinal = len(product_ids) + 1
            status, _, error, body = request(api, "POST", {"name": f"Redis Cache load pool {ordinal}", "price": 1.00, "category": "load-test", "description": "Generated by load test"}, args.timeout)
            if status != 201:
                print(f"Could not create random-read pool (HTTP {status}): {error or 'check application/database'}", file=sys.stderr)
                return 2
            product_ids.append(int(json.loads(body)["id"]))
        product_id = product_ids[0]
        print(f"Prepared {len(product_ids)} products for random reads.")
    elif product_id is None:
        status, _, error, body = request(api, "POST", {"name": "Redis Cache load test", "price": 1.00, "category": "load-test", "description": "Generated by load test"}, args.timeout)
        if status != 201:
            print(f"Could not create setup product (HTTP {status}): {error or 'check application/database'}", file=sys.stderr)
            return 2
        try:
            product_id = int(json.loads(body)["id"])
        except Exception as exc:
            print(f"Setup product was created, but its ID could not be read: {exc}", file=sys.stderr)
            return 2
        print(f"Created setup product; using ID {product_id}.")
    if args.setup_only:
        print(product_id)
        return 0

    if args.mode != "write":
        warm_ids = product_ids if args.mode == "random" else [product_id]
        for warm_id in warm_ids:
            warm_status, _, warm_error, _ = request(f"{api}/{warm_id}", timeout=args.timeout)
            if warm_status != 200:
                print(f"Warm-up failed for product {warm_id} (HTTP {warm_status}): {warm_error or 'check product ID'}", file=sys.stderr)
                return 2

    stop_at = time.monotonic() + args.duration
    start_barrier = threading.Barrier(args.concurrency)
    results: list[tuple[int | None, float, str | None]] = []
    result_lock = threading.Lock()
    sequence = iter(range(1, 10**12))
    sequence_lock = threading.Lock()
    rng = random.Random()

    def worker() -> None:
        local = []
        start_barrier.wait()
        while time.monotonic() < stop_at:
            if args.mode == "write":
                status, latency, error, _ = request(api, "POST", {"name": "Redis Cache load write", "price": 1.00, "category": "load-test", "description": "Generated by load test"}, args.timeout)
                local.append((status, latency, error))
                continue
            if args.mode == "warm":
                target = product_id
            elif args.mode == "random":
                target = rng.choice(product_ids)
            else:
                with sequence_lock:
                    n = next(sequence)
                target = product_id if args.mode == "mixed" and n % 2 == 0 else product_id + 1_000_000_000_000 + n
            status, latency, error, _ = request(f"{api}/{target}", timeout=args.timeout)
            local.append((status, latency, error))
        with result_lock:
            results.extend(local)

    wall_start = time.perf_counter()
    with concurrent.futures.ThreadPoolExecutor(max_workers=args.concurrency) as pool:
        futures = [pool.submit(worker) for _ in range(args.concurrency)]
        for future in futures:
            future.result()
    elapsed = time.perf_counter() - wall_start

    latencies = [r[1] for r in results]
    statuses = Counter(str(r[0]) if r[0] is not None else "network_error" for r in results)
    errors = Counter(r[2] for r in results if r[2])
    print(f"Target: {base}/api/products (mode={args.mode})" if args.mode == "write" else f"Target: {base}/api/products/{product_id} (mode={args.mode})")
    print(f"Duration: {elapsed:.2f}s | concurrency: {args.concurrency} | requests: {len(results)}")
    print(f"Throughput: {len(results) / elapsed:.2f} requests/s")
    if latencies:
        print("Latency (ms): " + ", ".join(f"{label}={value * 1000:.2f}" for label, value in (
            ("min", min(latencies)), ("median", statistics.median(latencies)),
            ("p95", percentile(latencies, .95)), ("p99", percentile(latencies, .99)),
            ("max", max(latencies)))))
    print("HTTP outcomes: " + ", ".join(f"{code}={count}" for code, count in sorted(statuses.items())))
    if errors:
        print("Network errors:")
        for message, count in errors.most_common(5):
            print(f"  {count} x {message}")
    if args.mode == "mixed":
        return 0 if not errors and sum(statuses.values()) == len(results) and set(statuses).issubset({"200", "404"}) else 1
    expected = Counter({"201": len(results)}) if args.mode == "write" else Counter({"404": len(results)}) if args.mode == "miss" else Counter({"200": len(results)})
    return 0 if statuses == expected else 1


if __name__ == "__main__":
    raise SystemExit(main())
